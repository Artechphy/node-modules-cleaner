#!/usr/bin/env python3
"""Safely audit and remove inactive node_modules directories."""

from __future__ import annotations

import argparse
import dataclasses
import datetime as dt
import fnmatch
import json
import os
import shutil
import sys
import tempfile
import time
from pathlib import Path
from typing import Optional, Sequence


KEEP_MARKER = ".node-modules-cleaner-keep"
PROJECT_ACTIVITY_FILES = (
    "package.json",
    "package-lock.json",
    "pnpm-lock.yaml",
    "yarn.lock",
    "npm-shrinkwrap.json",
    "bun.lock",
    "bun.lockb",
)
SECONDS_PER_DAY = 24 * 60 * 60


@dataclasses.dataclass(frozen=True)
class CleanerConfig:
    root: Path
    days: int = 30
    mode: str = "audit"
    exclusions: tuple[str, ...] = ()
    report_dir: Path = Path("reports/runtime")


@dataclasses.dataclass
class Activity:
    timestamp: float
    source: str
    size_bytes: Optional[int]


@dataclasses.dataclass
class CandidateResult:
    path: str
    status: str
    action: str
    reason: str
    last_activity_utc: Optional[str] = None
    inactive_days: Optional[float] = None
    size_bytes: Optional[int] = None


def utc_iso(timestamp: float) -> str:
    return dt.datetime.fromtimestamp(timestamp, tz=dt.timezone.utc).isoformat()


def path_is_within(path: Path, root: Path) -> bool:
    try:
        path.relative_to(root)
        return True
    except ValueError:
        return False


def validate_root(root: Path) -> Path:
    resolved = root.expanduser().resolve(strict=True)
    home = Path.home().resolve()
    if not resolved.is_dir():
        raise ValueError(f"scan root is not a directory: {resolved}")
    if resolved == Path(resolved.anchor) or resolved == home:
        raise ValueError("refusing to scan the filesystem root or the home directory")
    return resolved


def is_excluded(relative_path: str, exclusions: Sequence[str]) -> bool:
    normalized = relative_path.strip("/")
    return any(
        fnmatch.fnmatch(normalized, pattern.strip("/"))
        or fnmatch.fnmatch(f"{normalized}/", f"{pattern.strip('/')}/*")
        for pattern in exclusions
        if pattern.strip()
    )


def raise_walk_error(error: OSError) -> None:
    raise error


def discover_node_modules(root: Path, exclusions: Sequence[str]) -> list[Path]:
    candidates: list[Path] = []
    for current, dirnames, _filenames in os.walk(
        root, topdown=True, onerror=raise_walk_error, followlinks=False
    ):
        current_path = Path(current)
        kept_dirs: list[str] = []
        for dirname in dirnames:
            child = current_path / dirname
            relative = child.relative_to(root).as_posix()
            if child.is_symlink() or is_excluded(relative, exclusions):
                continue
            if dirname == "node_modules":
                candidates.append(child)
                continue
            kept_dirs.append(dirname)
        dirnames[:] = kept_dirs
    return sorted(candidates)


def stat_activity(path: Path) -> tuple[float, str]:
    stat = path.lstat()
    values = (
        (stat.st_atime, "atime"),
        (stat.st_mtime, "mtime"),
        (stat.st_ctime, "ctime"),
    )
    timestamp, kind = max(values, key=lambda item: item[0])
    return timestamp, f"{path}:{kind}"


def project_activity(candidate: Path) -> Activity:
    project = candidate.parent
    latest_timestamp = project.lstat().st_mtime
    latest_source = f"{project}:mtime"
    for filename in PROJECT_ACTIVITY_FILES:
        indicator = project / filename
        if not indicator.exists() or indicator.is_symlink():
            continue
        timestamp, source = stat_activity(indicator)
        if timestamp > latest_timestamp:
            latest_timestamp, latest_source = timestamp, source
    return Activity(latest_timestamp, latest_source, None)


def module_activity(candidate: Path, recent_threshold: float) -> Activity:
    root_stat = candidate.lstat()
    latest_timestamp = max(root_stat.st_mtime, root_stat.st_ctime)
    latest_source = f"{candidate}:mtime/ctime"
    if latest_timestamp >= recent_threshold:
        return Activity(latest_timestamp, latest_source, None)

    size_bytes = 0
    for current, dirnames, filenames in os.walk(
        candidate, topdown=True, onerror=raise_walk_error, followlinks=False
    ):
        current_path = Path(current)
        dirnames[:] = [
            name for name in dirnames if not (current_path / name).is_symlink()
        ]
        for filename in filenames:
            child = current_path / filename
            try:
                if child.is_symlink():
                    continue
                stat = child.lstat()
            except FileNotFoundError:
                continue
            size_bytes += stat.st_size
            timestamp, kind = max(
                ((stat.st_atime, "atime"), (stat.st_mtime, "mtime"), (stat.st_ctime, "ctime")),
                key=lambda item: item[0],
            )
            if timestamp > latest_timestamp:
                latest_timestamp = timestamp
                latest_source = f"{child}:{kind}"
            if timestamp >= recent_threshold:
                return Activity(latest_timestamp, latest_source, None)
    return Activity(latest_timestamp, latest_source, size_bytes)


def assess_candidate(candidate: Path, root: Path, threshold: float, now: float) -> CandidateResult:
    display_path = str(candidate)
    try:
        if candidate.is_symlink():
            return CandidateResult(display_path, "skipped", "none", "symbolic link")
        resolved = candidate.resolve(strict=True)
        if resolved.name != "node_modules" or not path_is_within(resolved, root):
            return CandidateResult(display_path, "skipped", "none", "failed safety boundary check")
        if (resolved.parent / KEEP_MARKER).exists() or (resolved / KEEP_MARKER).exists():
            return CandidateResult(display_path, "kept", "none", f"{KEEP_MARKER} marker present")

        project = project_activity(resolved)
        if project.timestamp >= threshold:
            return CandidateResult(
                display_path,
                "recent",
                "none",
                f"recent project activity: {project.source}",
                utc_iso(project.timestamp),
                round((now - project.timestamp) / SECONDS_PER_DAY, 2),
            )

        module = module_activity(resolved, threshold)
        latest = module if module.timestamp >= project.timestamp else project
        inactive_days = (now - latest.timestamp) / SECONDS_PER_DAY
        if latest.timestamp >= threshold:
            return CandidateResult(
                display_path,
                "recent",
                "none",
                f"recent dependency activity: {latest.source}",
                utc_iso(latest.timestamp),
                round(inactive_days, 2),
            )
        return CandidateResult(
            display_path,
            "eligible",
            "pending",
            f"no activity within {round((now - threshold) / SECONDS_PER_DAY)} days",
            utc_iso(latest.timestamp),
            round(inactive_days, 2),
            module.size_bytes,
        )
    except (OSError, ValueError) as exc:
        return CandidateResult(display_path, "error", "none", f"{type(exc).__name__}: {exc}")


def safe_delete(candidate: Path, root: Path) -> None:
    if candidate.is_symlink():
        raise ValueError("candidate became a symbolic link")
    resolved = candidate.resolve(strict=True)
    if resolved.name != "node_modules" or not path_is_within(resolved, root):
        raise ValueError("candidate failed final safety boundary check")
    shutil.rmtree(resolved)


def write_report(report_dir: Path, payload: dict, run_id: str) -> Path:
    report_dir.mkdir(parents=True, exist_ok=True)
    report_path = report_dir / f"cleanup-{run_id}.json"
    with tempfile.NamedTemporaryFile(
        mode="w", encoding="utf-8", dir=report_dir, prefix=".cleanup-", suffix=".tmp", delete=False
    ) as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=2, sort_keys=True)
        handle.write("\n")
        temporary_path = Path(handle.name)
    os.replace(temporary_path, report_path)
    return report_path


def run_cleanup(config: CleanerConfig, now: Optional[float] = None) -> tuple[dict, Path]:
    run_started = time.time() if now is None else now
    root = validate_root(config.root)
    if config.days < 1:
        raise ValueError("days must be at least 1")
    if config.mode not in {"audit", "apply"}:
        raise ValueError("mode must be audit or apply")

    threshold = run_started - (config.days * SECONDS_PER_DAY)
    candidates = discover_node_modules(root, config.exclusions)
    results: list[CandidateResult] = []
    for candidate in candidates:
        result = assess_candidate(candidate, root, threshold, run_started)
        if result.status == "eligible":
            if config.mode == "audit":
                result.action = "would-delete"
            else:
                try:
                    safe_delete(candidate, root)
                    result.action = "deleted"
                except (OSError, ValueError) as exc:
                    result.status = "error"
                    result.action = "delete-failed"
                    result.reason = f"{type(exc).__name__}: {exc}"
        results.append(result)

    summary = {
        "found": len(results),
        "eligible": sum(item.status == "eligible" for item in results),
        "deleted": sum(item.action == "deleted" for item in results),
        "would_delete": sum(item.action == "would-delete" for item in results),
        "kept_or_recent": sum(item.status in {"kept", "recent", "skipped"} for item in results),
        "errors": sum(item.status == "error" for item in results),
        "eligible_bytes": sum(item.size_bytes or 0 for item in results if item.status == "eligible"),
    }
    run_id = dt.datetime.fromtimestamp(run_started, tz=dt.timezone.utc).strftime("%Y%m%dT%H%M%S.%fZ")
    payload = {
        "schema_version": 1,
        "run_id": run_id,
        "started_at_utc": utc_iso(run_started),
        "root": str(root),
        "inactive_days": config.days,
        "mode": config.mode,
        "exclusions": list(config.exclusions),
        "summary": summary,
        "results": [dataclasses.asdict(item) for item in results],
    }
    report_path = write_report(config.report_dir, payload, run_id)
    return payload, report_path


def read_exclusions(path: Optional[Path]) -> tuple[str, ...]:
    if path is None:
        return ()
    lines = path.read_text(encoding="utf-8").splitlines()
    return tuple(line.strip() for line in lines if line.strip() and not line.lstrip().startswith("#"))


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.home() / "Documents")
    parser.add_argument("--days", type=int, default=30)
    parser.add_argument("--mode", choices=("audit", "apply"), default="audit")
    parser.add_argument("--exclude", action="append", default=[], help="root-relative glob; repeatable")
    parser.add_argument("--exclude-file", type=Path)
    parser.add_argument("--report-dir", type=Path, default=Path("reports/runtime"))
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = build_parser().parse_args(argv)
    exclusions = tuple(args.exclude) + read_exclusions(args.exclude_file)
    try:
        payload, report_path = run_cleanup(
            CleanerConfig(
                root=args.root,
                days=args.days,
                mode=args.mode,
                exclusions=exclusions,
                report_dir=args.report_dir,
            )
        )
    except (OSError, ValueError) as exc:
        print(f"fatal: {exc}", file=sys.stderr)
        return 2

    summary = payload["summary"]
    print(
        f"mode={payload['mode']} found={summary['found']} eligible={summary['eligible']} "
        f"deleted={summary['deleted']} would_delete={summary['would_delete']} errors={summary['errors']}"
    )
    print(f"report={report_path.resolve()}")
    return 1 if summary["errors"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
